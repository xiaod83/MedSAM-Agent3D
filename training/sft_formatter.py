import os
import json

def format_trajectories_for_sft(trajectories_dir, output_jsonl_path):
    """
    Converts trajectory JSONs generated by the pipeline into a JSONL format
    suitable for Supervised Fine-Tuning (SFT) using HuggingFace messages format.
    
    Compatible with Qwen3-VL's apply_chat_template and TRL.
    Uses standard messages format with multimodal content arrays.
    """
    system_prompt = "You are a 3D medical segmentation agent. You see three orthogonal slices [Axial | Coronal | Sagittal]. Output the correct tool call."
    
    formatted_data = []
    
    for filename in os.listdir(trajectories_dir):
        if not filename.endswith(".json"):
            continue
            
        file_path = os.path.join(trajectories_dir, filename)
        with open(file_path, 'r') as f:
            trajectory = json.load(f)
            
        for turn_key, turn_data in trajectory.items():
            image_path = turn_data.get("image", "")
            instruction = turn_data.get("instruction", "")
            action = turn_data.get("action", {})
            
            # Format the expected output JSON string
            action_str = json.dumps(action)
            
            # Normalize path separators to forward slashes for cross-platform compatibility
            image_path = image_path.replace("\\", "/")
            
            # Construct a conversation in HuggingFace standard messages format
            # Qwen3-VL apply_chat_template expects this format with multimodal content
            conversation = [
                {
                    "role": "system",
                    "content": system_prompt
                },
                {
                    "role": "user",
                    "content": [
                        {"type": "image"},
                        {"type": "text", "text": instruction}
                    ]
                },
                {
                    "role": "assistant",
                    "content": action_str
                }
            ]
            
            sample = {
                "images": [image_path],
                "conversations": conversation
            }
            formatted_data.append(sample)
            
    # Save to JSONL
    with open(output_jsonl_path, 'w', encoding='utf-8') as f:
        for item in formatted_data:
            f.write(json.dumps(item, ensure_ascii=False) + '\n')
            
    print(f"Formatted {len(formatted_data)} samples for SFT into {output_jsonl_path}")

if __name__ == "__main__":
    import sys
    if len(sys.argv) > 2:
        format_trajectories_for_sft(sys.argv[1], sys.argv[2])
    else:
        format_trajectories_for_sft("data/trajectories", "data/sft_dataset.jsonl")